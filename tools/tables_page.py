#!/usr/bin/env python3
"""Render every data/tables/<name>.json as a readable site page.

  site/tables/<name>.md          one page per table: notes, values (errata applied and marked), sources
  site/tables/index.md           every table, grouped by the rules page that cites it
  site/.vitepress/tables.json    name -> title and group, read by the sidebar and the prose-link plugin

Run by tools/gen_pages.py, so its "no diff left over" gate covers these pages. Presentation
only: the JSON is never written, and the values shown are the JSON's values with the
data/errata overlays applied (the engine applies the same overlays).
"""
import copy
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADER = "<!-- generated by tools/gen_pages.py (tools/tables_page.py); do not edit -->"
META_KEYS = {"table", "sources", "notes", "footnotes", "known_gaps"}

# Rules directories in reading order (the sidebar's order), each a group on the index.
GROUPS = [("rules", "Land Game"), ("rules/logistics", "Logistics Game"),
          ("rules/air", "Air Game"), ("rules/scenarios", "Scenarios")]

# Words kept as written when a key or value is turned into a label.
WORDS = {"cw": "CW", "de": "German", "it": "Italian", "cp": "CP", "cpa": "CPA", "toe": "TOE",
         "sp": "SP", "id": "Id", "hq": "HQ", "sgsu": "SGSU", "lrdg": "LRDG", "sas": "SAS",
         "aa": "AA", "et": "ET", "mot": "mot", "non": "non", "opstage": "Op stage",
         "tac": "Tac", "rp": "RP", "rommel": "Rommel", "malta": "Malta", "axis": "Axis", "tacair": "TacAir"}


# --- errata ------------------------------------------------------------------------

def _unescape(token):
    return token.replace("~1", "/").replace("~0", "~")


def _resolve(doc, parts):
    for p in parts:
        doc = doc[int(p)] if isinstance(doc, list) else doc[p]
    return doc


def apply_errata(table, patches):
    """Apply RFC 6902 add/remove/replace overlays. Returns (patched copy, {pointer: errata id})."""
    out = copy.deepcopy(table)
    marks = {}
    for e in patches:
        for op in e["patches"]:
            parts = [_unescape(t) for t in op["path"].lstrip("/").split("/")]
            parent, key = _resolve(out, parts[:-1]), parts[-1]
            if op["op"] == "replace":
                if isinstance(parent, list):
                    parent[int(key)] = op["value"]
                else:
                    parent[key] = op["value"]
            elif op["op"] == "add":
                if isinstance(parent, list):
                    parent.insert(len(parent) if key == "-" else int(key), op["value"])
                else:
                    parent[key] = op["value"]
            elif op["op"] == "remove":
                del parent[int(key) if isinstance(parent, list) else key]
            else:
                raise ValueError(f"{e['id']}: unsupported op {op['op']}")
            marks[op["path"]] = e["id"]
    return out, marks


# --- formatting ----------------------------------------------------------------------

def _compounds(s):
    return re.sub(r"\b(anti|non) (armour|aircraft|air|mot)\b", r"\1-\2", s, flags=re.I)


def label(key):
    """`cw_percent` -> 'CW percent', `anti_armour` -> 'Anti-armour'; `rows` is the table itself."""
    key = str(key)
    if key == "rows":
        return "Table"
    if re.fullmatch(r"[+-]?\d+", key):
        return key
    s = _compounds(" ".join(WORDS.get(w, w) for w in key.split("_")))
    return s[:1].upper() + s[1:]


def title_of(table):
    """The `table` field is a slug (`close-assault-results`); its label is the page title."""
    words = [WORDS.get(w, w) if w not in ("de", "it") else w for w in table["table"].split("-")]
    s = _compounds(" ".join(words))
    return s[:1].upper() + s[1:]


def _slug_value(s):
    """Enum slugs read as words: 'no-effect' -> 'no effect'. Ids, dice and signed numbers stay."""
    if re.fullmatch(r"[a-z]+(?:-[a-z]+)+", s):
        return s.replace("-", " ")
    return s


def _int_run(xs):
    return (len(xs) > 2 and all(isinstance(x, int) and not isinstance(x, bool) for x in xs)
            and xs == list(range(xs[0], xs[0] + len(xs))))


NATIONS = {"cw": "Commonwealth", "it": "Italian", "de": "German"}


def fmt(v, key=None):
    """One value as cell text (unescaped). `key` names the field: nation codes read as names."""
    if key in ("nation", "side") and v in NATIONS:
        return NATIONS[v]
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return _slug_value(v)
    if isinstance(v, list):
        if not v:
            return "none"
        if _int_run(v):
            return f"{v[0]}–{v[-1]}"
        return ", ".join(fmt(x) for x in v)
    if isinstance(v, dict):
        if set(v) <= {"from", "to"} and v:
            a, b = v.get("from"), v.get("to")
            if a is None:
                return f"up to {b}"
            if b is None:
                return f"{a}+"
            return f"{a}–{b}" if a != b else str(a)
        if set(v) <= {"min", "max"} and v:
            a, b = v.get("min"), v.get("max")
            if a is None:
                return f"≤ {b}"
            if b is None:
                return f"≥ {a}"
            return f"{a} to {b}"
        return "; ".join(f"{label(k)}: {fmt(x, k)}" for k, x in v.items() if k != "sources")
    return str(v)


def cell(text):
    """Escape cell text for a markdown table inside a Vue-compiled page. Cells don't wrap
    (custom.css) unless long, so CRT ranges stay on one line and wide tables scroll."""
    text = text.replace("\\", "\\\\").replace("|", "\\|").replace("<", "&lt;")
    text = text.replace("{", "&#123;").replace("}", "&#125;")
    text = re.sub(r"([*_`\[\]])", r"\\\1", text)
    text = text.replace("\n", " ")
    return f'<span class="wrap">{text}</span>' if len(text) > 40 else text


def prose(text):
    """Notes are our own markdown; only guard against Vue interpolation."""
    return text.replace("{{", "&#123;&#123;").replace("}}", "&#125;&#125;")


class Ctx:
    def __init__(self, marks, errata_href, columns=None):
        self.marks, self.href = marks, errata_href
        self.columns = columns if isinstance(columns, list) else []   # the table's column definitions

    def mark(self, pointer):
        """Errata ids whose patch path is this pointer, inside it, or encloses it."""
        ids = sorted({e for p, e in self.marks.items()
                      if p == pointer or p.startswith(pointer + "/") or pointer.startswith(p + "/")})
        return "".join(f' <a class="errata-mark" href="{self.href}" title="Corrected by errata {i}">{i}</a>'
                       for i in ids)

    def cell(self, value, pointer, key=None):
        if isinstance(value, dict) and not _leafish(value):   # one "Label: value" per line
            text = "<br>".join(cell(f"{label(k)}: {fmt(x, k)}") for k, x in value.items() if k != "sources")
        elif isinstance(value, list) and any(isinstance(x, (dict, list)) and not _leafish(x) for x in value):
            text = "<br>".join(cell(fmt(x)) for x in value)               # one object per line
        else:
            text = cell(fmt(value, key))
        return text + self.mark(pointer)


def _esc_ptr(k):
    return str(k).replace("~", "~0").replace("/", "~1")


# --- blocks ----------------------------------------------------------------------------

def _grid(rows, base, ctx, columns=None):
    keys = []
    for r in rows:
        for k in r:
            if k not in keys and k not in ("sources", "notes"):
                keys.append(k)
    has_notes = any(r.get("notes") for r in rows)
    # A field holding one value per table column (a dice row across the chart) spreads across
    # those columns, headed by the column definitions' first value.
    n = len(ctx.columns)
    spread = {k for k in keys if n > 4 and all(isinstance(r.get(k), list) and len(r[k]) == n for r in rows)}
    first = next(iter(ctx.columns[0]), "") if n and isinstance(ctx.columns[0], dict) else ""
    col_heads = [cell(fmt(next(iter(c.values())))) if isinstance(c, dict) else cell(fmt(c)) for c in ctx.columns]
    head = []
    for k in keys:   # "Bomb 1–20 | 21–40 | …": the first column names what the columns count
        head += [f"{label(first)} {h}" if j == 0 else h for j, h in enumerate(col_heads)] if k in spread else [label(k)]
    head += ["Notes"] if has_notes else []
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for i, r in enumerate(rows):
        cells = []
        for k in keys:
            if k in spread:
                cells += [ctx.cell(x, f"{base}/{i}/{_esc_ptr(k)}/{j}") for j, x in enumerate(r[k])]
            else:
                cells.append(ctx.cell(r.get(k), f"{base}/{i}/{_esc_ptr(k)}", k) if k in r else "")
        if has_notes:
            cells.append(cell(" ".join(r.get("notes") or [])))
        out.append("| " + " | ".join(cells) + " |")
    return out


def _pivot(rows, columns, base, ctx):
    """CRT rows of one cell each (`column` names a column id) -> row label x column grid."""
    col_ids = [c["id"] for c in columns]
    meta = ("column", "sources", "notes", "footnotes")
    value_key = [k for k in rows[0] if k not in meta][-1]
    label_keys = [k for k in rows[0] if k not in meta and k != value_key]
    order, grid = [], {}
    for i, r in enumerate(rows):
        lab = tuple(fmt(r.get(k), k) for k in label_keys)
        if lab not in grid:
            order.append(lab)
            grid[lab] = {}
        grid[lab][r["column"]] = ctx.cell(r[value_key], f"{base}/{i}/{_esc_ptr(value_key)}")
    head = [label(k) for k in label_keys] + [cell(str(c)) for c in col_ids]
    out = [f"*Each cell: {label(value_key).lower()}.*", "",
           "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for lab in order:
        out.append("| " + " | ".join([cell(x) for x in lab] + [grid[lab].get(c, "—") for c in col_ids]) + " |")
    return out


def _flat(v):
    return isinstance(v, dict) and all(_leafish(x) for x in v.values())


def _cellish(v, depth=0):
    """Fits in one table cell, one line per item: leaves, small objects of leaves, short lists of
    those (alternatives), nested at most three deep. A list of objects that themselves hold a list
    longer than four (a dice row across columns, say) is a table of its own, not a cell."""
    if isinstance(v, list) and len(v) > 4 and depth > 1:
        return False                        # a row of values across columns: tabular
    if _leafish(v):
        return True
    if depth >= 3 or v is None:
        return v is None
    if isinstance(v, dict):
        return all(_cellish(x, depth + 1) for x in v.values())
    return isinstance(v, list) and len(v) <= 20 and all(x is None or _cellish(x, depth + 1) for x in v)


def _is_matrix(v):
    return (isinstance(v, dict) and len(v) > 1 and all(isinstance(x, dict) and not _leafish(x) for x in v.values())
            and not any(isinstance(y, (dict, list)) and not _leafish(y)
                        for x in v.values() for y in x.values()))


def _leafish(v):
    """A value that formats as one cell: a scalar, a range, or a list of those."""
    if isinstance(v, dict):
        return bool(v) and set(v) <= {"from", "to", "min", "max"}
    if isinstance(v, list):
        return all(_leafish(x) and not isinstance(x, list) for x in v)
    return True


def _matrix(v, base, ctx, corner=""):
    cols = []
    for row in v.values():
        for k in row:
            if k not in cols:
                cols.append(k)
    head = [corner] + [cell(label(c)) for c in cols]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for rk, row in v.items():
        out.append("| " + " | ".join(
            [f"**{cell(label(rk))}**"] +
            [ctx.cell(row[c], f"{base}/{_esc_ptr(rk)}/{_esc_ptr(c)}") if c in row else "" for c in cols]) + " |")
    return out


def _block(key, value, base, ctx, level, siblings):
    """Markdown lines for one keyed value of a table."""
    ptr = f"{base}/{_esc_ptr(key)}"
    title = label(key)
    h = "#" * min(level, 6)
    if isinstance(value, list) and value and all(isinstance(r, dict) and not _leafish(r) for r in value):
        if any(not _cellish(x) for r in value for k, x in r.items() if k not in ("sources", "notes")):
            # rows that hold tables of their own: one subsection per row
            out = [f"{h} {title}", ""]
            for i, r in enumerate(value):
                name = " · ".join(fmt(x, k) for k, x in r.items()
                                  if k not in ("sources", "notes") and _leafish(x) and not isinstance(x, (dict, list)))
                out += _record(name or f"{title} {i + 1}", r, f"{ptr}/{i}", ctx, level + 1)
            return out
        cols = siblings.get("columns")
        if (key != "columns" and isinstance(cols, list) and cols and all(isinstance(c, dict) and "id" in c for c in cols)
                and all("column" in r for r in value)):
            return [f"{h} {title}", ""] + _pivot(value, cols, ptr, ctx) + [""]
        return [f"{h} {title}", ""] + _grid(value, ptr, ctx) + [""]
    if _is_matrix(value):
        return [f"{h} {title}", ""] + _matrix(value, ptr, ctx) + [""]
    if isinstance(value, dict) and any(isinstance(x, (dict, list)) and not _leafish(x) for x in value.values()):
        return _record(title, value, ptr, ctx, level)
    if isinstance(value, dict):
        return [f"{h} {title}", ""] + _scalars(value, ptr, ctx)
    return _scalars({key: value}, base, ctx)


def _record(title, value, ptr, ctx, level):
    """A heading, the record's simple values as a list, then each nested table under it."""
    h = "#" * min(level, 6)
    scalars = {k: x for k, x in value.items() if _leafish(x) and k not in ("sources", "notes")}
    out = [f"{h} {cell(title)}", ""] + _scalars(scalars, ptr, ctx)
    if value.get("notes") and isinstance(value["notes"], list):
        out += [prose(" ".join(value["notes"])), ""]
    for k, x in value.items():
        if k not in scalars and k not in ("sources", "notes"):
            out += _block(k, x, ptr, ctx, level + 1, value)
    return out


def _scalars(d, base, ctx):
    """Simple values as a list: "**Label:** value"."""
    if not d:
        return []
    return [f"- **{cell(label(k))}:** {ctx.cell(v, f'{base}/{_esc_ptr(k)}', k)}" for k, v in d.items()] + [""]


def sources_line(sources):
    parts = []
    for s in sources:
        if s.startswith("CNA1979:"):
            parts.append("SPI " + s.split(":", 1)[1])
        elif s.startswith("scan:p"):
            parts.append("scan page " + s.split("p", 1)[1])
        else:
            parts.append(s)
    return " · ".join(parts)


# --- pages -----------------------------------------------------------------------------

def render_table(name, table, errata, cited_by):
    """One table page. `errata`: overlay dicts for this table; `cited_by`: [(title, link)]."""
    data, marks = apply_errata(table, errata)
    ctx = Ctx(marks, "/data/errata/INDEX", data.get("columns"))
    title = title_of(table)
    out = ["---", f"title: {json.dumps(title)}", "pageClass: cna-table-page", "aside: false", "---", "", HEADER, "", f"# {prose(title)}", ""]
    if cited_by:
        out += ["Used in " + ", ".join(f"[{t}]({l})" for t, l in cited_by) + ".", ""]
    if errata:
        out += ["::: tip Errata applied",
                *[f"- **{e['id']}** — {prose(e['summary'])}" for e in errata],
                ":::", ""]
    for g in data.get("known_gaps") or []:
        where = ", ".join(f"{label(k).lower()} {fmt(x, k)}" for k, x in g.items() if k not in ("readings", "sources"))
        out += ["::: warning Gap in the printed chart",
                f"As printed, no result covers dice readings {cell(fmt(g.get('readings')))} ({cell(where)}). "
                "The notes below say how this edition handles it.", ":::", ""]
    keys = [k for k in data if k not in META_KEYS]
    for k in sorted(keys, key=lambda k: k == "columns"):   # a CRT's column definitions follow its results
        out += _block(k, data[k], "", ctx, 2, data)
    if data.get("notes"):
        out += ["## Notes", ""] + [f"- {prose(n)}" for n in data["notes"]] + [""]
    if data.get("footnotes"):
        out += ["## Footnotes", ""]
        out += [f"{k}. {prose(str(v))}" for k, v in data["footnotes"].items()] + [""]
    out += ["---", "",
            f"<p class=\"table-sources\">Sources: {cell(sources_line(table.get('sources', [])))}. "
            f"Data: <a href=\"https://github.com/basmith7/cna/blob/main/data/tables/{name}.json\">"
            f"data/tables/{name}.json</a> (CC0).</p>", ""]
    return "\n".join(out)


def citations(root):
    """table name -> [(rules page title, link, group index)] in reading order."""
    found = {}
    for gi, (d, _) in enumerate(GROUPS):
        for p in sorted((root / d).glob("*.md")):
            md = p.read_text()
            if md.startswith(HEADER) or "do not edit" in md[:200]:
                continue
            t = re.search(r"^title:\s*(.+?)\s*$", md, re.M)
            title = t.group(1) if t else p.stem
            link = "/" + str(p.relative_to(root).with_suffix(""))
            for n in dict.fromkeys(re.findall(r"data/tables/([\w-]+)\.json", md)):
                found.setdefault(n, []).append((title, link, gi))
    return found


def render_index(meta):
    out = ["---", "title: Tables", "pageClass: tables-index", "---", "", HEADER, "", "# Tables", "",
           "Every chart and table the rules call for, with SPI's September 1979 errata applied. "
           "Each page lists the rules that use it. Rules pages link here wherever a table is "
           "named, and search (Ctrl K) finds a table by its name.", "",
           "For developers: the same values are JSON in `data/tables/`; see the "
           "[data conventions](/data/).", ""]
    for g in [*(n for _, n in GROUPS), "Other"]:
        rows = [(n, m) for n, m in meta.items() if m["group"] == g]
        if not rows:
            continue
        out += [f"## {g}", "", "| Table | Used in |", "|---|---|"]
        for n, m in sorted(rows, key=lambda r: r[1]["title"].lower()):
            used = ", ".join(f"[{t}]({l})" for t, l in m["cited_by"]) or "—"
            out.append(f"| [{cell(m['title'])}](/tables/{n}) | {used} |")
        out.append("")
    return "\n".join(out)


def targets(root=ROOT):
    """{path: text} for every generated file."""
    cites = citations(root)
    errata = {}
    for p in sorted((root / "data" / "errata").glob("E-*.json")):
        e = json.loads(p.read_text())
        errata.setdefault(e["table"], []).append(e)
    t, meta = {}, {}
    for p in sorted((root / "data" / "tables").glob("*.json")):
        name = p.stem
        table = json.loads(p.read_text())
        cited = [(title, link) for title, link, _ in cites.get(name, [])]
        group = GROUPS[cites[name][0][2]][1] if name in cites else "Other"
        meta[name] = {"title": title_of(table), "group": group, "cited_by": cited}
        t[root / "site" / "tables" / f"{name}.md"] = render_table(name, table, errata.get(name, []), cited)
    t[root / "site" / "tables" / "index.md"] = render_index(meta)
    t[root / "site" / ".vitepress" / "tables.json"] = json.dumps(
        {n: {"title": m["title"], "group": m["group"]} for n, m in meta.items()}, indent=1, ensure_ascii=False) + "\n"
    return t
